/* ============================================================
 AIProvenance — tracks which fields were generated by AI and
 whether the user has reviewed/edited them.

 Loaded as a plain <script>. Attaches to window.AIProv.

 Storage: state.meta.aiProv = { "path.string": {ai:true, confirmed:false, ts:...} }
 - Paths are dot-separated with array items keyed by id:
   "work1.environment.political"
   "work1.environment.competitors[c_abc].name"
 - Persists with the rest of state (server-backed store).
 - Survives rerender and page reload.

 Public API:
   AIProv.mark(path)              — flag a field as AI-sourced
   AIProv.markMany(prefix, keys)  — flag several fields under a prefix
   AIProv.confirm(path)           — user has reviewed/edited this field
   AIProv.isAi(path)              — true if AI-sourced (regardless of confirmed)
   AIProv.isConfirmed(path)       — true if AI-sourced AND user-confirmed
   AIProv.badge(path)             — returns a small <span> "AI" badge or null
   AIProv.forScope(prefix)        — returns a scoped helper:
       s.isAi(key), s.mark(key), s.confirm(key), s.badge(key), s.markMany(keys)
                                    (paths are auto-prefixed)
   AIProv.strip(obj)              — recursively removes __aiProv meta when
                                    exporting data (defensive; the store lives
                                    under state.meta so it is normally excluded)

 The badge DOM:
   <span class="ai-badge" title="...">AI</span>            (unconfirmed)
   <span class="ai-badge confirmed" title="...">AI</span>  (user-confirmed)
 Clicking the badge toggles confirmed state and rerenders the current step.
 ============================================================ */
(function(){
 'use strict';

 function store(){
   if(typeof state==='undefined') return null;
   if(!state.meta) state.meta={};
   if(!state.meta.aiProv) state.meta.aiProv={};
   return state.meta.aiProv;
 }

 function mark(path){
   const s=store(); if(!s) return;
   s[path]={ai:true, confirmed:false, ts:Date.now()};
 }

 function markMany(prefix, keys){
   keys.forEach(k=>mark(prefix+'.'+k));
 }

 function confirm(path){
   const s=store(); if(!s||!s[path]) return;
   s[path].confirmed=true;
 }

 function isAi(path){
   const s=store(); return !!(s && s[path] && s[path].ai);
 }

 function isConfirmed(path){
   const s=store(); return !!(s && s[path] && s[path].ai && s[path].confirmed);
 }

 // Build a badge element. Returns null if the path is not AI-sourced.
 function badge(path, opts){
   if(!isAi(path)) return null;
   const confirmed=isConfirmed(path);
   const b=document.createElement('span');
   b.className='ai-badge'+(confirmed?' confirmed':'');
   b.textContent='AI';
   b.title=confirmed
     ? 'AI 生成，你已确认。点击撤销确认。'
     : 'AI 生成，尚未确认。编辑该字段或点击此处标记为已确认。';
   b.addEventListener('click', function(e){
     e.stopPropagation();
     if(confirmed){
       // un-confirm
       const s=store(); if(s && s[path]) s[path].confirmed=false;
     }else{
       confirm(path);
     }
     // rerender current step if the App shell is available
     if(typeof App!=='undefined' && App.currentWork && App.currentStep){
       const mod={1:Work1,2:Work2,3:Work3,4:Work4,5:Work5}[App.currentWork];
       if(mod && mod.rerender) mod.rerender(App.currentStep);
     }
     if(typeof autosave==='function') autosave();
   });
   return b;
 }

 // Scoped helper — avoids repeating long prefix strings in render functions.
 function forScope(prefix){
   return {
     isAi:      function(key){ return isAi(prefix+'.'+key); },
     mark:      function(key){ mark(prefix+'.'+key); },
     markMany:  function(keys){ markMany(prefix, keys); },
     confirm:   function(key){ confirm(prefix+'.'+key); },
     isConfirmed:function(key){ return isConfirmed(prefix+'.'+key); },
     badge:     function(key, opts){ return badge(prefix+'.'+key, opts); }
   };
 }

 // Recursively strip provenance from an exported object (defensive).
 function strip(obj){
   if(Array.isArray(obj)) return obj.map(strip);
   if(obj && typeof obj==='object'){
     const out={};
     for(const k of Object.keys(obj)){
       if(k==='__ai'||k==='__confirmed') continue;
       out[k]=strip(obj[k]);
     }
     return out;
   }
   return obj;
 }

 // ---- Section-level helper ---------------------------------------
 // A "section" is a UI block that was AI-generated in one shot (e.g. the
 // whole environment analysis). Marking the section path covers all its
 // fields. Editing any field inside the container confirms the section.
 //
 // Usage in a render function:
 //   sec.appendChild(AIProv.sectionBadge('work1.environment'));
 //   AIProv.watchSection(sec, 'work1.environment');
 // In onResult after AI fills data:
 //   AIProv.mark('work1.environment');

 // Section badge: one badge for the whole AI-generated block.
 function sectionBadge(scope){
   const b=badge(scope);
   if(b) b.setAttribute('data-ai-scope', scope);
   return b;
 }

 // Listen for any edit inside `container`; on first edit, mark the section
 // as user-confirmed (badge turns to outline style).
 function watchSection(container, scope){
   if(!container || !scope) return;
   function onEdit(){
     if(isAi(scope) && !isConfirmed(scope)){
       confirm(scope);
       const b=container.querySelector('.ai-badge[data-ai-scope="'+cssEscape(scope)+'"]');
       if(b) b.classList.add('confirmed');
       if(typeof autosave==='function') autosave();
     }
   }
   container.addEventListener('input', onEdit);
   container.addEventListener('change', onEdit);
 }

 function cssEscape(s){
   if(window.CSS && CSS.escape) return CSS.escape(s);
   return String(s).replace(/[^a-zA-Z0-9_-]/g, c=>'\\'+c);
 }

 const AIProv={
   mark, markMany, confirm, isAi, isConfirmed, badge, forScope, strip,
   sectionBadge: sectionBadgeWithAttr, watchSection
 };
 if(typeof window!=='undefined') window.AIProv=AIProv;
 if(typeof module!=='undefined' && module.exports) module.exports=AIProv;
})();
